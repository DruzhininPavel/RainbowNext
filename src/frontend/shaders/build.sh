#!/bin/sh
# Turns the GLSL sources into the two blobs SDL_GPU can load: SPIR-V for Vulkan
# and MSL for Metal. Both are checked in, so building RainbowNext does not need
# a shader compiler -- only changing a shader does:
#
#   brew install glslang spirv-cross        # macOS
#   apt install glslang-tools spirv-cross   # Debian/Ubuntu
#   src/frontend/shaders/build.sh
set -eu

here=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

for stage in vert frag; do
  glslangValidator -V --target-env vulkan1.0 "$here/crt.$stage" -o "$tmp/crt.$stage.spv" > /dev/null
  # SDL_GPU looks for an entry point called main0 in MSL, and GLSL calls it main.
  spirv-cross "$tmp/crt.$stage.spv" --msl --rename-entry-point main main0 "$stage" \
    --output "$tmp/crt.$stage.msl"
done

python3 - "$tmp" "$here/crt_shaders.h" <<'PY'
import sys
from pathlib import Path

tmp = Path(sys.argv[1])
out = Path(sys.argv[2])

def blob(stage):
    data = (tmp / f"crt.{stage}.spv").read_bytes()
    body = ", ".join(f"0x{b:02x}" for b in data)
    return "\n".join(body[i:i + 96] for i in range(0, len(body), 96))

def source(stage):
    return (tmp / f"crt.{stage}.msl").read_text()

text = f"""// Generated by build.sh from crt.vert and crt.frag -- do not edit by hand.
#pragma once

#include <cstdint>

namespace rainbow::frontend::shaders {{

inline constexpr std::uint8_t kCrtVertSpirv[] = {{
{blob("vert")}
}};

inline constexpr std::uint8_t kCrtFragSpirv[] = {{
{blob("frag")}
}};

inline constexpr char kCrtVertMsl[] = R"MSL({source("vert")})MSL";

inline constexpr char kCrtFragMsl[] = R"MSL({source("frag")})MSL";

}} // namespace rainbow::frontend::shaders
"""
out.write_text(text)
print(f"wrote {out} ({len(text)} bytes)")
PY
